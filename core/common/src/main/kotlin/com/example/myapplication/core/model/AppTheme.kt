package com.example.myapplication.core.model

/**
 * Represents the theme that the app should use.
 */
enum class AppTheme {
    /**
     * The app should use the theme that is currently set on the system.
     */
    DEFAULT,

    /**
     * The app should always use the light theme.
     */
    LIGHT,

    /**
     * The app should always use the dark theme.
     */
    DARK,
}
